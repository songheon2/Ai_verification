    doc.querySelector('#neuronFilter').value = '';
    doc.querySelector('#statusFilter').value = 'FINAL';
    doc.querySelector('#statusFilter').dispatchEvent(new win.Event('change'));
    assert(summaries().length === 3 && details(1).open && details(105).open && details(110) && !details(2) && !details(108), 'final-result filter shows only the last exploration path');
    assert(doc.querySelectorAll('#timeline .row').length === 3, 'timeline follows the same final-result path filter');
    doc.querySelector('#statusFilter').value = 'SAT_FOUND';
    doc.querySelector('#statusFilter').dispatchEvent(new win.Event('change'));
    doc.querySelector('#layerFilter').value = '999';
    doc.querySelector('#layerFilter').dispatchEvent(new win.Event('input'));
    doc.querySelector('#neuronFilter').value = '999';
    doc.querySelector('#neuronFilter').dispatchEvent(new win.Event('input'));
    assert(!details(110), 'latest branch is initially hidden by filters');
    doc.querySelector('#recentPath').click();
    assert(doc.querySelector('#statusFilter').value === 'ALL' && !doc.querySelector('#layerFilter').value && !doc.querySelector('#neuronFilter').value, 'recent path clears obstructing filters');
    assert(details(1).open && details(105).open && details(110), 'recent path reaches latest branch after completion');
    assert(!details(3) && !details(4), 'recent path keeps unrelated descendants collapsed');
    assert(doc.querySelectorAll('#tree details.recent-path').length === 3, 'entire latest path is highlighted');
    assert(details(110).classList.contains('recent-target') && !details(108).classList.contains('recent-target'), 'highlight moves to the newest branch');
    assert(doc.activeElement === details(110).querySelector('summary'), 'recent path focuses the destination');
    assert(growth(1).hidden && growth(105).hidden, 'filtered path navigation acknowledges ancestor growth');
    details(110).querySelector('summary').click();
    assert(growth(110).hidden && growth(105).hidden && growth(1).hidden, 'clicking leaf clears the full ancestor path');

