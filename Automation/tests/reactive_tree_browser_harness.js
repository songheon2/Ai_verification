    doc.querySelector('#stableScope').dispatchEvent(new win.Event('change'));
    assert(doc.querySelectorAll('#stableRows tr[data-id]').length === 1 && doc.querySelector('#stableRows').textContent.includes('L1:N99'), 'initial STABLE records can be viewed separately');
    assert(doc.querySelector('#stableRows tr[data-id]').cells[2].textContent === '활성(+)', 'active STABLE state includes plus sign');
    doc.querySelector('#stableScope').value = 'additional';
    doc.querySelector('#stableScope').dispatchEvent(new win.Event('change'));
    await click(1);
    assert(summaries().length === 3, 'root click creates only immediate children');
    assert(!details(3), 'grandchild is not drawn early');
    await click(2);
    assert(details(3) && !details(4), 'child click creates next level only');
    await click(3);
    assert(details(4), 'selected descendant materialized');
    await click(1);
    assert(summaries().length === 1 && !details(2) && !details(4), 'collapse removes descendant DOM');
    await click(1);
    assert(details(2).open && details(3).open && details(4), 'reopening restores nested expansion choices');

    const rootElement = details(1), childElement = details(2), unchangedLabel = details(3).querySelector('.label');
