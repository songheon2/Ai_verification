    assert(details(105).querySelector('.branch-growth').textContent === '+2', 'collapsed branch updates growth without rendering children');
    assert(win.getComputedStyle(growth(105)).color === greenColor, 'growth never alternates color');
    assert(!details(109) && !details(110), 'growth badge does not materialize new children');
    doc.querySelector('#defaultView').click();
    assert(summaries().length === 1, 'root-only action releases expanded DOM');
    doc.querySelector('#expandAll').click();
    assert(summaries().length === 110 && details(3).open && details(4) && details(105).open, 'expand-all action opens every level of the current tree');
    assert(growth(105).textContent === '+2', 'recreated DOM restores unread growth');

    doc.querySelector('#statusFilter').value = 'CLOSED_UNSAT';
