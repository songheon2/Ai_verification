    assert(doc.querySelectorAll('#timeline .row').length === 50, 'timeline DOM is bounded');
    assert(doc.querySelector('#stableHelp').textContent.startsWith('stable:'), 'tree includes concise STABLE count explanation');
    assert(!doc.querySelector('#stableOrder option[value="source"]') && doc.querySelector('#stableOrder option[value="node"]'), 'confirmation-node order replaces method order');
    assert(!doc.querySelector('#stableRows tr[data-id]'), 'additional STABLE view starts empty');
