    assert(!details(1) && details(2) && details(3) && !details(4), 'CLOSED filter shows matching nodes without unrelated ancestors or discoveries');
    assert([...doc.querySelectorAll('#tree details')].every(node => !node.open && node.classList.contains('leaf')), 'filtered matches are independent rows');
    assert(!doc.querySelector('#tree .badge.UNSAT_FOUND'), 'CLOSED filter excludes directly discovered conflicts');
