    assert(!auto.checked, 'final snapshot disables automatic refresh');
    assert(details(1).querySelector('.branch-growth').textContent === '+2', 'ancestor counts new branches after acknowledgement');
    assert(details(105).querySelector('.branch-growth').textContent === '+2', 'collapsed branch updates growth without rendering children');
    assert(win.getComputedStyle(growth(105)).color === greenColor, 'growth never alternates color');
    assert(!details(109) && !details(110), 'growth badge does not materialize new children');
    doc.querySelector('#defaultView').click();
    assert(summaries().length === 1, 'root-only action releases expanded DOM');
    doc.querySelector('#expandAll').click();
    assert(summaries().length === 110 && details(3).open && details(4) && details(105).open, 'expand-all action opens every level of the current tree');
    assert(growth(105).textContent === '+2', 'recreated DOM restores unread growth');

    doc.querySelector('#statusFilter').value = 'CLOSED_UNSAT';
    doc.querySelector('#statusFilter').dispatchEvent(new win.Event('change'));
    assert(!details(1) && details(2) && details(3) && !details(4), 'CLOSED filter shows matching nodes without unrelated ancestors or discoveries');
    assert([...doc.querySelectorAll('#tree details')].every(node => !node.open && node.classList.contains('leaf')), 'filtered matches are independent rows');
    assert(!doc.querySelector('#tree .badge.UNSAT_FOUND'), 'CLOSED filter excludes directly discovered conflicts');
    doc.querySelector('#statusFilter').value = 'UNSAT_FOUND';
    doc.querySelector('#statusFilter').dispatchEvent(new win.Event('change'));
    assert(!details(1) && !details(2) && !details(3) && details(4) && details(110), 'discovery filter shows only matching discoveries without ancestor paths');
    doc.querySelector('#statusFilter').value = 'ALL';
    doc.querySelector('#statusFilter').dispatchEvent(new win.Event('change'));
    doc.querySelector('#layerFilter').value = '3';
    doc.querySelector('#layerFilter').dispatchEvent(new win.Event('input'));
    assert(summaries().length > 1 && summaries().every(row => row.querySelector('.label').textContent.startsWith('L3:')) && !details(1) && !details(105), 'layer filter shows matching nodes without ancestors');
    doc.querySelector('#neuronFilter').value = '201';
    doc.querySelector('#neuronFilter').dispatchEvent(new win.Event('input'));
    assert(summaries().length === 1 && details(106), 'neuron filter isolates its matching node');
    doc.querySelector('#layerFilter').value = '';
    doc.querySelector('#neuronFilter').value = '';
    doc.querySelector('#statusFilter').value = 'FINAL';
    doc.querySelector('#statusFilter').dispatchEvent(new win.Event('change'));
    assert(summaries().length === 3 && details(1).open && details(105).open && details(110) && !details(2) && !details(108), 'final-result filter shows only the last exploration path');
    assert(doc.querySelectorAll('#timeline .row').length === 3, 'timeline follows the same final-result path filter');
    doc.querySelector('#statusFilter').value = 'SAT_FOUND';
    doc.querySelector('#statusFilter').dispatchEvent(new win.Event('change'));
    doc.querySelector('#layerFilter').value = '999';
    doc.querySelector('#layerFilter').dispatchEvent(new win.Event('input'));
    doc.querySelector('#neuronFilter').value = '999';
    doc.querySelector('#neuronFilter').dispatchEvent(new win.Event('input'));
    assert(!details(110), 'latest branch is initially hidden by filters');
    doc.querySelector('#recentPath').click();
    assert(doc.querySelector('#statusFilter').value === 'ALL' && !doc.querySelector('#layerFilter').value && !doc.querySelector('#neuronFilter').value, 'recent path clears obstructing filters');
    assert(details(1).open && details(105).open && details(110), 'recent path reaches latest branch after completion');
    assert(!details(3) && !details(4), 'recent path keeps unrelated descendants collapsed');
    assert(doc.querySelectorAll('#tree details.recent-path').length === 3, 'entire latest path is highlighted');
    assert(details(110).classList.contains('recent-target') && !details(108).classList.contains('recent-target'), 'highlight moves to the newest branch');
    assert(doc.activeElement === details(110).querySelector('summary'), 'recent path focuses the destination');
    assert(growth(1).hidden && growth(105).hidden, 'filtered path navigation acknowledges ancestor growth');
    details(110).querySelector('summary').click();
    assert(growth(110).hidden && growth(105).hidden && growth(1).hidden, 'clicking leaf clears the full ancestor path');

