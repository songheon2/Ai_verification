    await click(105);
    assert(details(106), 'new snapshot child is created when requested');
    assert(growth(105).hidden, 'click acknowledges this branch growth');
    assert(growth(1).hidden, 'clicking child also clears ancestor growth immediately');
    await click(105);
    assert(!details(106), 'newly created subtree is released on collapse');

    assert(growth(105).hidden, 'acknowledged growth stays cleared after collapsing');
    await refresh();
    assert(growth(1).hidden, 'unchanged snapshot does not restore acknowledged ancestor growth');
    assert(growth(105).hidden, 'unchanged snapshot does not restore acknowledged growth');

