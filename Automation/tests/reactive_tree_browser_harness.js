    doc.querySelector('#layerFilter').dispatchEvent(new win.Event('input'));
    assert(summaries().length > 1 && summaries().every(row => row.querySelector('.label').textContent.startsWith('L3:')) && !details(1) && !details(105), 'layer filter shows matching nodes without ancestors');
    doc.querySelector('#neuronFilter').value = '201';
    doc.querySelector('#neuronFilter').dispatchEvent(new win.Event('input'));
    assert(summaries().length === 1 && details(106), 'neuron filter isolates its matching node');
